// Regenerates src/sitemap.xml and prerender-routes.txt from the app's real
// routes and content data, so neither drifts out of sync again.
//
//   npm run seo:generate
//
// Blog slugs and city slugs are read from blog.data.ts / city-landing.data.ts.
// Languages without long-form content (nl) get every page with translated UI,
// but blog articles and city pages only exist in CONTENT_LANGS — their nl URLs
// canonicalise to English, so they are left out of the sitemap.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const BASE = 'https://karaarslan-bike.de';
const LANGS = ['de', 'en', 'fr', 'tr', 'nl'];
const CONTENT_LANGS = ['de', 'en', 'fr', 'tr'];
const today = new Date().toISOString().slice(0, 10);

const blogBase = (l) => (l === 'de' || l === 'tr' ? 'ratgeber' : 'guide');

// ── Read slugs from the data files ──
const blogSrc = readFileSync(join(root, 'src/app/services/blog.data.ts'), 'utf8');
const articles = [];
for (const m of blogSrc.matchAll(/^\s{4}slug: '([^']+)',\s*\n\s{4}slugTranslations: \{([^}]*)\}/gm)) {
  const tr = Object.fromEntries(
    [...m[2].matchAll(/(\w+): '([^']+)'/g)].map((x) => [x[1], x[2]]),
  );
  articles.push((l) => tr[l] ?? m[1]);
}
const citySrc = readFileSync(join(root, 'src/app/services/city-landing.data.ts'), 'utf8');
const cities = [...citySrc.matchAll(/^\s{4}slug: '(fahrrad-[^']+)'/gm)].map((m) => m[1]);

// ── Page groups: one entry per page, path per language ──
const page = (path, priority, changefreq, langs = LANGS) => ({
  langs,
  path: (l) => `/${l}${path ? '/' + path : ''}`,
  priority,
  changefreq,
});
const groups = [
  page('', '1.0', 'daily'),
  page('showroom', '0.97', 'daily'),
  page('gebrauchte-fahrraeder', '0.95', 'daily'),
  page('neue-fahrraeder', '0.9', 'weekly'),
  page('weihnachtsgeschenk-fahrrad', '0.9', 'weekly'),
  page('fahrradgroesse-berechnen', '0.85', 'monthly'),
  page('kinderfahrrad-alter', '0.85', 'monthly'),
  page('zubehoer', '0.8', 'weekly'),
  page('faq', '0.75', 'monthly'),
  page('about', '0.7', 'monthly'),
  page('contact', '0.7', 'monthly'),
  page('garantie', '0.4', 'yearly'),
  { langs: LANGS, path: (l) => `/${l}/${blogBase(l)}`, priority: '0.8', changefreq: 'weekly' },
  ...articles.map((slug) => ({
    langs: CONTENT_LANGS,
    path: (l) => `/${l}/${blogBase(l)}/${slug(l)}`,
    priority: '0.7',
    changefreq: 'monthly',
  })),
  ...cities.map((c) => page(c, '0.75', 'monthly', CONTENT_LANGS)),
];

// ── sitemap.xml ──
let xml = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/generate-seo-files.mjs — do not edit by hand -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"
        xmlns:xhtml="http://www.w3.org/1999/xhtml">
`;
for (const g of groups) {
  const alternates = g.langs
    .map((l) => `    <xhtml:link rel="alternate" hreflang="${l}" href="${BASE}${g.path(l)}"/>`)
    .concat(`    <xhtml:link rel="alternate" hreflang="x-default" href="${BASE}${g.path('de')}"/>`)
    .join('\n');
  for (const l of g.langs) {
    xml += `  <url>
    <loc>${BASE}${g.path(l)}</loc>
${alternates}
    <lastmod>${today}</lastmod>
    <changefreq>${g.changefreq}</changefreq>
    <priority>${g.priority}</priority>
  </url>
`;
  }
}
xml += '</urlset>\n';
writeFileSync(join(root, 'src/sitemap.xml'), xml);

// ── prerender-routes.txt ──
const legal = ['impressum', 'datenschutz'];
const routes = new Set();
for (const g of groups) for (const l of g.langs) routes.add(g.path(l));
for (const l of LANGS) for (const p of legal) routes.add(`/${l}/${p}`);
writeFileSync(join(root, 'prerender-routes.txt'), [...routes].join('\n') + '\n');

console.log(
  `sitemap.xml: ${xml.match(/<url>/g).length} URLs · prerender-routes.txt: ${routes.size} routes · ${articles.length} articles · ${cities.length} cities`,
);
